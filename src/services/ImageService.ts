/**
 * Get the image URL for a Turkish answer key.
 * Returns a curated Unsplash URL, or null (caller falls back to EmojiImage).
 */
export function getImageUrl(key: string): string | null {
  if (!key) return null;

  const normalized = key.toLowerCase().trim();

  if (CURATED[normalized]) return CURATED[normalized];

  // Try underscore → space variant
  const spaced = normalized.replace(/_/g, ' ');
  if (CURATED[spaced]) return CURATED[spaced];

  return null;
}

/**
 * Get image URL for an AnswerOption by its text.
 */
export function getImageUrlForOption(optionText: string): string | null {
  return getImageUrl(optionText);
}
